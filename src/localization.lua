local GAME_LOCALE_TO_LANGUAGE = {
    enUS = "enUS",
    enGB = "enUS",
    ptPT = "ptPT",
    frFR = "frFR",
    deDE = "deDE",
    itIT = "itIT",
    jaJP = "jaJP",
}

local LANGUAGE_NAMES = {
    enUS = "English",
    ptPT = "Português (Portugal)",
    frFR = "Français",
    deDE = "Deutsch",
    itIT = "Italiano",
    jaJP = "日本語",
}

local validLanguages = {
    auto = true,
    enUS = true,
    ptPT = true,
    frFR = true,
    deDE = true,
    itIT = true,
    jaJP = true,
}

local systemLocale = type(GetLocale) == "function" and GetLocale() or "enUS"

function HAOF.GetLanguagePreference()
    local savedLanguage = HAOF_Settings and HAOF_Settings.Language
    return validLanguages[savedLanguage] and savedLanguage or "auto"
end

function HAOF.SetLanguagePreference(language)
    if not validLanguages[language] then
        return false
    end

    local settings = HAOF.SettingsManager and HAOF.SettingsManager:GetOptions()
    if not settings then
        HAOF_Settings = HAOF_Settings or {}
        settings = HAOF_Settings
    end
    settings.Language = language
    return settings.Language == language
end

function HAOF.GetLanguageName(language)
    if language == "auto" then
        local activeLanguage = GAME_LOCALE_TO_LANGUAGE[systemLocale] or "enUS"
        return string.format(HAOF.T("Automatic (%s)"), LANGUAGE_NAMES[activeLanguage])
    end
    return LANGUAGE_NAMES[language] or LANGUAGE_NAMES.enUS
end

function HAOF.ApplyLanguage(language)
    if not validLanguages[language] then
        language = "auto"
    end

    local activeLanguage = language == "auto"
        and (GAME_LOCALE_TO_LANGUAGE[systemLocale] or "enUS")
        or language

    HAOF.ActiveLanguage = activeLanguage
    HAOF.Locale = locales[activeLanguage] or locales.enUS
end

HAOF.ApplyLanguage(HAOF.GetLanguagePreference())

function HAOF.T(text)
    return HAOF.Locale[text] or text
end
